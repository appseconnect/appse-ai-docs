import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const DOCS_ROOT = path.join(process.cwd(), "docs");
const OUTPUT = path.join(process.cwd(), "redirects.generated.ts");

function parseFrontmatter(content) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return {};
  const data = {};
  for (const line of match[1].split("\n")) {
    const idx = line.indexOf(":");
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    let value = line.slice(idx + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    data[key] = value;
  }
  return data;
}

function gitGrep(pattern) {
  try {
    return execSync(`git grep -h "${pattern}" -- docs`, {
      encoding: "utf8",
    });
  } catch {
    return "";
  }
}

function gitGrepWithPaths(pattern) {
  try {
    return execSync(`git grep "${pattern}" -- docs`, {
      encoding: "utf8",
    });
  } catch {
    return "";
  }
}

/** Parse `docs/path/file.md:matched content` from git grep output. */
function parseGitGrepLine(line) {
  const match = line.match(/^(docs[/\\].+?):(.*)$/);
  if (!match) return null;
  return { filePart: match[1], rest: match[2] };
}

function defaultUrlFromFile(relPath) {
  const withoutExt = relPath.replace(/\.(md|mdx)$/, "");
  const segments = withoutExt.split(/[/\\]/);
  return `/${segments.join("/")}`;
}

function normalizeSlug(slug) {
  let s = slug.trim();
  if (!s.startsWith("/")) s = `/${s}`;
  if (s.length > 1 && s.endsWith("/")) s = s.slice(0, -1);
  return s;
}

function walk(dir, base = "") {
  const redirects = new Map();

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      for (const [k, v] of walk(fullPath, rel)) redirects.set(k, v);
      continue;
    }

    if (!/\.(md|mdx)$/.test(entry.name)) continue;
    if (entry.name === "index.md" || entry.name === "index.mdx") continue;

    const defaultUrl = defaultUrlFromFile(rel);
    const kebabUrl = `/${rel
      .replace(/\.(md|mdx)$/, "")
      .split(/[/\\]/)
      .map((segment) => segment.replace(/_/g, "-"))
      .join("/")}`;
    if (kebabUrl !== defaultUrl) {
      redirects.set(kebabUrl, defaultUrl);
    }

    const content = fs.readFileSync(fullPath, "utf8");
    const fm = parseFrontmatter(content);
    if (fm.slug) {
      const legacy = normalizeSlug(fm.slug);
      if (legacy !== defaultUrl) {
        redirects.set(legacy, defaultUrl);
      }
    }
  }

  return redirects;
}

function addGitSlugs(redirects) {
  const lines = gitGrepWithPaths("^slug:");
  for (const line of lines.split("\n").filter(Boolean)) {
    const parsed = parseGitGrepLine(line);
    if (!parsed) continue;
    const slugMatch = parsed.rest.match(/slug:\s*(.+)/);
    if (!slugMatch) continue;

    const relPath = parsed.filePart
      .replace(/^docs[/\\]/, "")
      .replace(/\\/g, "/");
    if (relPath.includes("_category_.json")) continue;

    const legacy = normalizeSlug(slugMatch[1].trim());
    const defaultUrl = defaultUrlFromFile(relPath);
    if (legacy !== defaultUrl) {
      redirects.set(legacy, defaultUrl);
    }
  }
}

function addCategorySlugs(redirects) {
  const lines = gitGrepWithPaths('"slug"');
  for (const line of lines.split("\n").filter(Boolean)) {
    if (!line.includes("_category_.json")) continue;
    const slugMatch = line.match(/"slug":\s*"([^"]+)"/);
    if (!slugMatch) continue;

    const parsed = parseGitGrepLine(line);
    if (!parsed) continue;
    const dir = parsed.filePart
      .replace(/^docs[/\\]/, "")
      .replace(/[/\\]_category_\.json$/, "")
      .replace(/\\/g, "/");

    const legacy = normalizeSlug(slugMatch[1]);
    const folderUrl = defaultUrlFromFile(`${dir}/index.md`);
    if (legacy !== folderUrl) {
      redirects.set(legacy, folderUrl);
    }
  }
}

const redirects = new Map();
for (const [k, v] of walk(DOCS_ROOT)) redirects.set(k, v);
addGitSlugs(redirects);
addCategorySlugs(redirects);

const lines = [...redirects.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([source, destination]) =>
      `  { source: ${JSON.stringify(source)}, destination: ${JSON.stringify(destination)}, permanent: true },`,
  );

const file = `import type { Redirect } from "next/dist/lib/load-custom-routes";

/** Auto-generated by pnpm migrate:redirects — do not edit manually */
export const legacyRedirects: Redirect[] = [
${lines.join("\n")}
];
`;

fs.writeFileSync(OUTPUT, file);
console.log(`Wrote ${redirects.size} redirects to redirects.generated.ts`);
